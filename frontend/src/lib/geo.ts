/** Finds the division and upazila / city corporation for a district and thana or union, for pre-filling. */
export function locateArea(district: string, area: string): { division?: string; district?: string; upazila?: string; area?: string; seat?: string } {
  for (const [division, districts] of Object.entries(GEO)) {
    const upazilas = districts[district];
    if (!upazilas) continue;
    for (const [upazila, node] of Object.entries(upazilas)) {
      if (area in node.subs) return { division, district, upazila, area, seat: node.seats.length === 1 ? node.seats[0] : "" };
    }
    return { division, district };
  }
  return {};
}
